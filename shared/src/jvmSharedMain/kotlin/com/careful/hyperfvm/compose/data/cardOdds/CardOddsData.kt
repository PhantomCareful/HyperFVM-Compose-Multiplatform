    /** 解析一行预设：星级钳进该位范围（越界/缺失回退 -1），类型/四叶草按名字映射，非法回退 -1。 */
    private fun parsePreset(line: String): Preset {
        val parts = line.split("|")
        val category = mapOf("好卡" to 2, "中卡" to 1, "差卡" to 0)
        // 名字未能匹配时 indexOfFirst 为 -1，同样要回退 -1（不选），不能直接减 1
        val cloverIndex = FourLeafCloverNames.indexOfFirst { it == parts.getOrNull(8)?.trim() }
        return Preset(
            title = parts[0].trim(),
            main = parseStar(parts.getOrNull(1), 15),
            sub1 = parseStar(parts.getOrNull(2), 16),
            sub1Category = category[parts.getOrNull(3)?.trim()] ?: -1,
            sub2 = parseStar(parts.getOrNull(4), 16),
            sub2Category = category[parts.getOrNull(5)?.trim()] ?: -1,
            sub3 = parseStar(parts.getOrNull(6), 16),
            sub3Category = category[parts.getOrNull(7)?.trim()] ?: -1,
            clover = if (cloverIndex >= 1) cloverIndex - 1 else -1,
        )
    }

    /** 星级字段解析：数字且落在 [0, max] 内才有效，其余（含「不选」）回退 -1。 */
    private fun parseStar(text: String?, max: Int): Int {
        val value = text?.trim()?.toIntOrNull() ?: return -1
        return if (value in 0..max) value else -1
    }
